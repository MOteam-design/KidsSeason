/* Курс «Енот Чек» — сверх лимита недели. 100 ₽ за каждый пройденный урок (один раз).
   Общий файл для Саши, Дани и Семёна. Список уроков — как в Академии (chek-trainer.html, LESSONS). */
(function () {
  "use strict";
  window.ENOT = {
    URL: "https://moteam-design.github.io/enot-chek/",
    PTS: 100,
    LESSONS: [
      [1, "Знакомство и азбука логики"],
      [2, "Азбука логики: часть 2"],
      [3, "Факт или мнение"],
      [4, "Суперсила вопросов"],
      [5, "Осторожно, мошенники"],
      [6, "Ловушки в рассуждениях"],
      [7, "Ловушки-2 и неверные выводы"],
      [8, "Как мозг нас обманывает"],
      [9, "Проверка новостей"],
      [10, "Итоговый тест"]
    ],
    // en: {номер урока: дата прохождения}, ev: {номер: 0 — родитель не засчитал, 1 — засчитал}
    // Возвращает сумму за уроки, пройденные с from по to (ISO-даты), без отклонённых.
    sum(en, ev, from, to) {
      let n = 0; const list = [];
      Object.keys(en || {}).forEach(k => {
        const d = en[k];
        if (d >= from && d <= to && !(ev && ev[k] === 0)) { n++; list.push(+k); }
      });
      return { n, sum: n * this.PTS, list: list.sort((a, b) => a - b) };
    }
  };
})();
